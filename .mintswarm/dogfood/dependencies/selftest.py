#!/usr/bin/env python3
"""Offline self-test of new-packages.py, the lockfile diff for the dependency review.

    selftest.py

Needs `git` and `yq` on PATH; nothing else, and no network. It works in a
`tempfile.mkdtemp` directory with its own HOME, no system or global git
config and a fixed identity, on a throwaway repository with no remote.
Fixtures are whole-tree commits built with git plumbing; configs and
lockfiles are written inline, configs and pnpm lockfiles as JSON text.
new-packages.py runs as `sys.executable -I -B new-packages.py ...` with that
repository as its working directory.

Cases: the option absent and `off`; `agent` with only a docs change; a
Cargo change (a new registry crate, an upgrade, a git crate, a look-alike
registry, a new transitive crate, a new workspace member); a pnpm change (an
upgraded scoped package, a tarball package, a peer-suffixed key); a
Cargo.toml without a lockfile change; an unreadable pnpm-lock.yaml; a changed
.npmrc; an unknown option value and bad arguments; the checkout's own
config; identical output on two runs; Python 3.9 syntax and standard-library
imports only.

Prints one `ok` or `FAIL` line per check, then a count, and exits 0 only
when all passed.
"""

import ast
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPT = HERE / "new-packages.py"
CHECKOUT_CONFIG = HERE.parent.parent / "config.yaml"
CONFIG = ".mintswarm/config.yaml"
CRATES = "registry+https://github.com/rust-lang/crates.io-index"
GIT_SOURCE = "git+https://example.invalid/gitdep#0123456789abcdef"
EVIL = "registry+https://github.com/rust-lang/crates.io-index-evil"
TARBALL = "https://example.invalid/tarpkg-1.0.0.tgz"
STDLIB = frozenset("argparse ast json os re shutil subprocess sys tempfile pathlib".split())


class SelfTest:
    def __init__(self):
        self.failed = 0
        self.passed = 0

    def check(self, name: str, condition: bool, detail: str = "") -> bool:
        if condition:
            self.passed += 1
            print(f"ok   {name}")
        else:
            self.failed += 1
            print(f"FAIL {name}" + (f": {detail}" if detail else ""))
        return condition


T = SelfTest()


# --- fixtures ---------------------------------------------------------------


def config(review=None) -> bytes:
    pipeline = {"review": {"max_rounds": 3}}
    if review is not None:
        pipeline["dependencies"] = {"review": review}
    return json.dumps({"pipeline": pipeline}).encode("utf-8")


def cargo_package(name: str, version: str, source: str = None, dependencies: list = None) -> str:
    text = f'[[package]]\nname = "{name}"\nversion = "{version}"\n'
    if source is not None:
        text += f'source = "{source}"\nchecksum = "00"\n'
    if dependencies is not None:
        text += "dependencies = [\n" + "".join(f' "{d}",\n' for d in dependencies) + "]\n"
    return text


def cargo_lock(*packages: str) -> bytes:
    return ("# This file is automatically @generated by Cargo.\nversion = 4\n\n" + "\n".join(packages)).encode("utf-8")


CARGO_BASE = cargo_lock(
    cargo_package("app", "0.1.0", dependencies=["serde"]),
    cargo_package("serde", "1.0.0", CRATES),
)
CARGO_HEAD = cargo_lock(
    cargo_package("anyhow", "1.0.0", CRATES, dependencies=["cc"]),
    cargo_package("app", "0.1.0", dependencies=["anyhow", "gitdep", "lookalike", "serde 1.0.1"]),
    cargo_package("cc", "1.0.0", CRATES),
    cargo_package("gitdep", "0.2.0", GIT_SOURCE),
    cargo_package("lookalike", "0.1.0", EVIL),
    cargo_package("serde", "1.0.0", CRATES),
    cargo_package("serde", "1.0.1", CRATES),
    cargo_package("tool", "0.1.0", dependencies=["serde 1.0.0 (" + CRATES + ")"]),
)


def pnpm_lock(dependencies: dict, packages: dict) -> bytes:
    lock = {"lockfileVersion": "9.0", "importers": {".": {"dependencies": dependencies}}, "packages": packages}
    return json.dumps(lock, indent=1).encode("utf-8")


PNPM_BASE = pnpm_lock(
    {"@scope/pkg": {"specifier": "^1.0.0", "version": "1.1.0"}},
    {"@scope/pkg@1.1.0": {"resolution": {"integrity": "sha512-a"}}, "react@18.0.0": {"resolution": {"integrity": "x"}}},
)
PNPM_HEAD = pnpm_lock(
    {
        "@scope/pkg": {"specifier": "^1.0.0", "version": "1.2.0"},
        "react-dom": {"specifier": "^18.0.0", "version": "18.0.0(react@18.0.0)"},
        "tarpkg": {"specifier": TARBALL, "version": TARBALL},
    },
    {
        "@scope/pkg@1.2.0": {"resolution": {"integrity": "sha512-b"}},
        "react-dom@18.0.0(react@18.0.0)": {"resolution": {"integrity": "sha512-c"}},
        "react@18.0.0": {"resolution": {"integrity": "x"}},
        f"tarpkg@{TARBALL}": {"resolution": {"tarball": TARBALL}, "version": "1.0.0"},
    },
)


def package(ecosystem, lockfile, name, version, source, registry, direct, previous=()) -> dict:
    return {
        "ecosystem": ecosystem,
        "lockfile": lockfile,
        "name": name,
        "version": version,
        "previous": list(previous),
        "source": source,
        "registry": registry,
        "direct": direct,
    }


CARGO_EXPECTED = [
    package("cargo", "Cargo.lock", "anyhow", "1.0.0", CRATES, True, True),
    package("cargo", "Cargo.lock", "cc", "1.0.0", CRATES, True, False),
    package("cargo", "Cargo.lock", "gitdep", "0.2.0", GIT_SOURCE, False, True),
    package("cargo", "Cargo.lock", "lookalike", "0.1.0", EVIL, False, True),
    package("cargo", "Cargo.lock", "serde", "1.0.1", CRATES, True, True, ["1.0.0"]),
]
PNPM_EXPECTED = [
    package("npm", "web/pnpm-lock.yaml", "@scope/pkg", "1.2.0", "registry", True, True, ["1.1.0"]),
    package("npm", "web/pnpm-lock.yaml", "react-dom", "18.0.0", "registry", True, True),
    package("npm", "web/pnpm-lock.yaml", "tarpkg", TARBALL, TARBALL, False, True),
]


class Sandbox:
    def __init__(self, tmp: Path):
        self.tmp = tmp
        self.repo = tmp / "repo"
        home = tmp / "home"
        for directory in (self.repo, home):
            directory.mkdir()
        env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
        env.update(
            {
                "HOME": str(home),
                "PYTHONDONTWRITEBYTECODE": "1",
                "GIT_CONFIG_NOSYSTEM": "1",
                "GIT_CONFIG_GLOBAL": os.devnull,
                "GIT_AUTHOR_NAME": "dependencies selftest",
                "GIT_AUTHOR_EMAIL": "selftest@example.invalid",
                "GIT_COMMITTER_NAME": "dependencies selftest",
                "GIT_COMMITTER_EMAIL": "selftest@example.invalid",
                "GIT_AUTHOR_DATE": "2026-01-01T00:00:00Z",
                "GIT_COMMITTER_DATE": "2026-01-01T00:00:00Z",
            }
        )
        self.env = env
        self.counter = 0
        self.git("init", "-q", "-b", "master")

    def raw(self, *args: str, data: bytes = None, env: dict = None) -> bytes:
        proc = subprocess.run(["git", *args], cwd=self.repo, env=env or self.env, input=data, capture_output=True)
        if proc.returncode != 0:
            raise RuntimeError(f"git {' '.join(args)} failed: {proc.stderr.decode(errors='replace').strip()}")
        return proc.stdout

    def git(self, *args: str, data: bytes = None) -> str:
        return self.raw(*args, data=data).decode("utf-8").strip()

    def commit(self, files: dict) -> str:
        """Commit files ({path: bytes}) as the whole tree."""
        self.counter += 1
        records = b""
        for path, data in sorted(files.items()):
            sha = self.git("hash-object", "-w", "--stdin", data=data)
            records += f"100644 {sha}\t".encode("utf-8") + path.encode("utf-8") + b"\0"
        env = dict(self.env, GIT_INDEX_FILE=str(self.tmp / f"index-{self.counter}"))
        self.raw("update-index", "-z", "--index-info", data=records, env=env)
        tree = self.raw("write-tree", env=env).decode("ascii").strip()
        return self.git("commit-tree", tree, "-m", f"fixture {self.counter}")

    def run(self, args: list) -> tuple:
        """Run the script; return (proc, packages.json as a dict or None)."""
        self.counter += 1
        out = self.tmp / f"out-{self.counter}"
        proc = subprocess.run(
            [sys.executable, "-I", "-B", str(SCRIPT), *args, "--out", str(out)],
            cwd=self.repo,
            env=self.env,
            capture_output=True,
        )
        target = out / "packages.json"
        return proc, (json.loads(target.read_text(encoding="utf-8")) if target.exists() else None)

    def diff(self, base_files: dict, head_files: dict) -> tuple:
        base, head = self.commit(base_files), self.commit(head_files)
        proc, result = self.run(["--base", base, "--head", head])
        return proc, result, base, head


def text(proc) -> str:
    return proc.stdout.decode("utf-8", errors="replace").strip()


# --- cases ------------------------------------------------------------------


def option_off(box: Sandbox):
    for label, value in (("absent", None), ("off", "off")):
        proc, result, _, _ = box.diff(
            {CONFIG: config(value), "Cargo.lock": CARGO_BASE}, {CONFIG: config(value), "Cargo.lock": CARGO_HEAD}
        )
        T.check(f"option {label}: exit 0", proc.returncode == 0, proc.stderr.decode(errors="replace"))
        T.check(f"option {label}: prints off", text(proc) == "dependency review: off", text(proc))
        T.check(f"option {label}: no output file", result is None)


def docs_only(box: Sandbox):
    proc, result, _, _ = box.diff(
        {CONFIG: config("agent"), "README.md": b"a\n"}, {CONFIG: config("agent"), "README.md": b"b\n"}
    )
    T.check("docs change: exit 0", proc.returncode == 0)
    T.check("docs change: prints no dependency change", text(proc) == "no dependency change", text(proc))
    T.check("docs change: no output file", result is None)


def cargo_change(box: Sandbox):
    proc, result, base, head = box.diff(
        {CONFIG: config("agent"), "Cargo.lock": CARGO_BASE}, {CONFIG: config("agent"), "Cargo.lock": CARGO_HEAD}
    )
    T.check("cargo: exit 0", proc.returncode == 0, proc.stderr.decode(errors="replace"))
    if not T.check("cargo: output written", result is not None):
        return
    T.check("cargo: keys", sorted(result) == ["base", "changed", "head", "packages", "problems"], str(sorted(result)))
    T.check("cargo: base and head are commits", result["base"] == base and result["head"] == head)
    T.check("cargo: changed", result["changed"] == ["Cargo.lock"], str(result["changed"]))
    T.check("cargo: packages", result["packages"] == CARGO_EXPECTED, json.dumps(result["packages"], indent=1))
    T.check("cargo: no problems", result["problems"] == [], str(result["problems"]))


def pnpm_change(box: Sandbox):
    proc, result, _, _ = box.diff(
        {CONFIG: config("agent"), "web/pnpm-lock.yaml": PNPM_BASE},
        {CONFIG: config("agent"), "web/pnpm-lock.yaml": PNPM_HEAD, "web/package.json": b"{}\n"},
    )
    T.check("pnpm: exit 0", proc.returncode == 0, proc.stderr.decode(errors="replace"))
    if not T.check("pnpm: output written", result is not None):
        return
    T.check("pnpm: changed", result["changed"] == ["web/package.json", "web/pnpm-lock.yaml"], str(result["changed"]))
    T.check("pnpm: packages", result["packages"] == PNPM_EXPECTED, json.dumps(result["packages"], indent=1))
    T.check("pnpm: no problems", result["problems"] == [], str(result["problems"]))


def manifest_without_lockfile(box: Sandbox):
    proc, result, _, _ = box.diff(
        {CONFIG: config("agent"), "crates/a/Cargo.toml": b"[package]\n", "Cargo.lock": CARGO_BASE},
        {
            CONFIG: config("agent"),
            "crates/a/Cargo.toml": b"[package]\n[dependencies]\nx = '1'\n",
            "Cargo.lock": CARGO_BASE,
        },
    )
    T.check("manifest only: exit 0", proc.returncode == 0)
    problems = result["problems"] if result else None
    expected = [{"path": "crates/a/Cargo.toml", "problem": "manifest changed with no Cargo.lock change"}]
    T.check("manifest only: problem recorded", problems == expected, str(problems))
    T.check("manifest only: no packages", result is not None and result["packages"] == [])


def unreadable_lockfile(box: Sandbox):
    proc, result, _, _ = box.diff(
        {CONFIG: config("agent"), "pnpm-lock.yaml": PNPM_BASE},
        {CONFIG: config("agent"), "pnpm-lock.yaml": b"packages: [unterminated\n", "Cargo.lock": b"\xff\xfe\n"},
    )
    T.check("unreadable: exit 0", proc.returncode == 0, proc.stderr.decode(errors="replace"))
    problems = result["problems"] if result else []
    paths = [p["path"] for p in problems]
    T.check("unreadable: both lockfiles in problems", paths == ["Cargo.lock", "pnpm-lock.yaml"], str(problems))
    T.check(
        "unreadable: the head side is named",
        all(p["problem"].startswith("cannot read the head lockfile") for p in problems),
        str(problems),
    )
    T.check("unreadable: no packages", result is not None and result["packages"] == [])


def npmrc_change(box: Sandbox):
    proc, result, _, _ = box.diff(
        {CONFIG: config("agent")},
        {CONFIG: config("agent"), ".npmrc": b"registry=https://example.invalid/\n", "x/.cargo/config.toml": b"\n"},
    )
    T.check("npmrc: exit 0", proc.returncode == 0)
    changed = result["changed"] if result else None
    T.check("npmrc: listed in changed", changed == [".npmrc", "x/.cargo/config.toml"], str(changed))
    T.check("npmrc: nothing else", result is not None and result["packages"] == [] and result["problems"] == [])


def bad_input(box: Sandbox):
    proc, result, _, _ = box.diff(
        {CONFIG: config("maybe"), "Cargo.lock": CARGO_BASE}, {CONFIG: config("maybe"), "Cargo.lock": CARGO_HEAD}
    )
    T.check("unknown value: exit 2", proc.returncode == 2, text(proc))
    T.check("unknown value: names the key", b"pipeline.dependencies.review" in proc.stderr)
    T.check("unknown value: no output file", result is None)
    head = box.commit({CONFIG: config("agent")})
    for label, args in (
        ("no --base", ["--head", head]),
        ("unknown argument", ["--base", head, "--head", head, "--bogus"]),
        ("missing ref", ["--base", "no-such-ref", "--head", head]),
    ):
        proc, result = box.run(args)
        T.check(f"{label}: exit 2", proc.returncode == 2, text(proc))
        T.check(f"{label}: no output file", result is None)
    no_config = box.commit({"README.md": b"x\n"})
    proc, result = box.run(["--base", no_config, "--head", head])
    T.check("base without config: exit 2", proc.returncode == 2, text(proc))


def checkout_config(box: Sandbox):
    own = CHECKOUT_CONFIG.read_bytes()
    proc, result, _, _ = box.diff({CONFIG: own}, {CONFIG: own, "Cargo.lock": CARGO_HEAD})
    T.check("checkout config: reads agent", proc.returncode == 0 and result is not None, text(proc))


def determinism(box: Sandbox):
    base = box.commit({CONFIG: config("agent"), "Cargo.lock": CARGO_BASE, "pnpm-lock.yaml": PNPM_BASE})
    head = box.commit({CONFIG: config("agent"), "Cargo.lock": CARGO_HEAD, "pnpm-lock.yaml": PNPM_HEAD})
    first, a = box.run(["--base", base, "--head", head])
    second, b = box.run(["--base", base, "--head", head])
    same_summary = text(first).split(":")[0] == text(second).split(":")[0]  # the rest is the --out path
    T.check("determinism: identical output", a is not None and a == b and same_summary)


def source_rules():
    for path in (SCRIPT, Path(__file__).resolve()):
        tree = ast.parse(path.read_text(encoding="utf-8"), feature_version=(3, 9))
        modules = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                modules.update(alias.name.split(".")[0] for alias in node.names)
            elif isinstance(node, ast.ImportFrom):
                modules.add((node.module or "").split(".")[0])
        T.check(f"{path.name}: standard library only", modules <= STDLIB, str(sorted(modules - STDLIB)))


def main() -> int:
    for tool in ("git", "yq"):
        if shutil.which(tool) is None:
            print(f"FAIL {tool} is not on PATH")
            return 1
    tmp = Path(tempfile.mkdtemp(prefix="msw-dependencies-"))
    try:
        box = Sandbox(tmp)
        for case in (
            option_off,
            docs_only,
            cargo_change,
            pnpm_change,
            manifest_without_lockfile,
            unreadable_lockfile,
            npmrc_change,
            bad_input,
            checkout_config,
            determinism,
        ):
            case(box)
        source_rules()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print(f"{T.passed} passed, {T.failed} failed")
    return 0 if T.failed == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
